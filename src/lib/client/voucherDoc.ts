"use client";
import QRCode from "qrcode";
import type { Booking, Voucher } from "@/lib/types";
import { inr } from "./i18n";

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]!);

export const qrSvg = (text: string) => QRCode.toString(text, { type: "svg", margin: 1, width: 132, errorCorrectionLevel: "M" });

const ICON: Record<Voucher["kind"], string> = { flight: "✈️", hotel: "🏨", transfer: "🚖", sightseeing: "📍" };

/** Standalone, printable HTML document for a booking's vouchers (works offline once saved). */
export async function vouchersHtml(b: Booking): Promise<string> {
  const qrs = await Promise.all(b.vouchers.map((v) => qrSvg(v.qrText)));
  const cards = b.vouchers
    .map(
      (v, i) => `<section class="v">
  <div class="qr">${qrs[i]}</div>
  <div class="body">
    <div class="kind">${ICON[v.kind]} ${esc(v.kind.toUpperCase())} VOUCHER</div>
    <div class="title">${esc(v.details)}</div>
    <div class="meta">Voucher code <b>${esc(v.code)}</b> · Valid ${esc(v.validFrom)}${v.validTo !== v.validFrom ? ` → ${esc(v.validTo)}` : ""}</div>
    <div class="meta">PNR ${esc(b.pnr)} · Lead guest ${esc(b.leadGuest.name)} · ${esc(b.leadGuest.phone)}</div>
  </div>
</section>`,
    )
    .join("\n");
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>TBO Saathi vouchers · ${esc(b.pnr)}</title>
<style>
  body{font-family:system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;color:#1c1917;margin:24px;background:#fff}
  header{display:flex;justify-content:space-between;align-items:flex-end;border-bottom:3px solid #0f766e;padding-bottom:8px;margin-bottom:16px}
  h1{margin:0;font-size:22px;color:#0f766e} .sub{color:#57534e;font-size:13px}
  .v{display:flex;gap:16px;align-items:center;border:1.5px dashed #0f766e;border-radius:12px;padding:12px;margin:0 0 12px;page-break-inside:avoid}
  .qr svg{width:120px;height:120px} .kind{font-size:11px;font-weight:700;color:#0f766e;letter-spacing:.06em}
  .title{font-size:16px;font-weight:600;margin:2px 0 4px} .meta{font-size:12px;color:#57534e}
  footer{margin-top:18px;font-size:11px;color:#78716c}
</style></head><body>
<header><div><h1>TBO Saathi · Travel Vouchers</h1><div class="sub">Booking ${esc(b.id)} · ${b.status === "cancelled" ? "CANCELLED" : "Confirmed"}</div></div>
<div class="sub">PNR <b>${esc(b.pnr)}</b><br>Paid ${esc(inr(b.paidINR))}</div></header>
${cards}
<footer>Show the QR code or voucher code at check-in. Demo booking generated by TBO Saathi — not valid for travel.</footer>
</body></html>`;
}

export async function downloadVouchers(b: Booking) {
  const html = await vouchersHtml(b);
  const url = URL.createObjectURL(new Blob([html], { type: "text/html" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = `TBO-vouchers-${b.pnr}.html`;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

/** Opens the print dialog (Save as PDF). The window is opened synchronously to avoid popup blockers. */
export function printVouchers(b: Booking) {
  const w = window.open("", "_blank");
  if (!w) return;
  void vouchersHtml(b).then((html) => {
    w.document.open();
    w.document.write(html);
    w.document.close();
    w.focus();
    setTimeout(() => w.print(), 300);
  });
}
